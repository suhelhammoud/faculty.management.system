export type Label = keyof typeof arabic;
export type Language = 'en' | 'ar';
export const LanguageContext = createContext<Language>('en');

export function useLanguage() {
  const language = useContext(LanguageContext);
  const t = (key: Label) => (language === 'ar' ? arabic[key] : key);
  const year = (value: number | null) =>
    value === null
      ? t('Unassigned')
      : language === 'ar'
        ? `السنة ${new Intl.NumberFormat('ar').format(value)}`
        : `Year ${value}`;
  const dateTime = (value: string) =>
    new Intl.DateTimeFormat(language, {
      calendar: 'gregory',
      year: 'numeric',
      month: 'short',
      day: 'numeric',
      hour: 'numeric',
      minute: '2-digit',
      timeZoneName: 'short',
    }).format(new Date(value));
  return { language, t, year, dateTime };
}
